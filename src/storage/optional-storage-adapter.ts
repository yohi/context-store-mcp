/**
 * オプショナルストレージアダプターインターフェース
 * 
 * Liteモードでの優雅な劣化をサポートするため、
 * オプション依存関係（Neo4j、Redisなど）の可用性チェックと
 * 初期化・シャットダウンのライフサイクル管理を提供します。
 * 
 * 要件: 1.2, 1.3, 11.1, 11.2
 */

/**
 * オプショナルストレージアダプターインターフェース
 * 
 * このインターフェースを実装することで、ストレージアダプターは
 * Liteモードでの優雅な劣化をサポートできます。
 */
export interface OptionalStorageAdapter {
  /**
   * ストレージアダプターが利用可能かどうかを確認
   * 
   * @returns ストレージが利用可能な場合true、そうでない場合false
   * 
   * 実装例:
   * - Neo4jの場合: 接続が確立されているか、Liteモードで無効化されていないか
   * - Redisの場合: 接続が確立されているか、Liteモードで無効化されていないか
   */
  isAvailable(): boolean;

  /**
   * ストレージアダプターを初期化
   * 
   * Liteモードが有効な場合、または依存関係が利用できない場合は、
   * エラーをスローせずに警告をログに記録して正常に完了する必要があります。
   * 
   * @throws {Error} 致命的なエラーが発生した場合（Liteモード以外）
   * 
   * 実装例:
   * - Neo4jの場合: Liteモードまたは接続失敗時は警告をログに記録して続行
   * - Redisの場合: Liteモードまたは接続失敗時は警告をログに記録して続行
   */
  initialize(): Promise<void>;

  /**
   * ストレージアダプターを優雅にシャットダウン
   * 
   * リソースを解放し、接続を閉じます。
   * ストレージが利用できない場合でも、エラーをスローせずに正常に完了する必要があります。
   * 
   * @throws {Error} シャットダウン中に致命的なエラーが発生した場合
   * 
   * 実装例:
   * - 接続が確立されている場合のみクローズ処理を実行
   * - 既にクローズされている場合は何もしない
   */
  gracefulShutdown(): Promise<void>;
}
